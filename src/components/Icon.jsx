/*
 * Monochrome line icons, replacing the emoji that used to sit beside titles.
 *
 * Why keyed by emoji. The book data still says `icon: '⚡'`, and this maps that
 * to a drawing. Doing it here rather than rewriting 67 `icon:` fields across
 * the data files means no content churn, one place to add a glyph, and the
 * emoji keeps working as the semantic key. **Anything unmapped falls back to
 * rendering the emoji itself** — the same degrade-don't-break rule ClubBanner
 * uses, so a new section is never iconless, just not yet drawn.
 *
 * Why one `d` per shape and circles drawn as arcs: every icon is then the same
 * primitive, so the component is four lines and there is no per-icon markup to
 * get wrong. All are built on a 24×24 grid with a 1.75 stroke, no fill, and
 * `currentColor` — which is what makes them black on the light theme and white
 * on the dark one without a second set or a single media query.
 */

