/*
 * `name` is the emoji from the data. Size follows the font size by default so
 * an icon sits on the text baseline at whatever scale its context uses.
 */
export default function Icon({ name, className = '' }) {
  const shapes = ICONS[name]
  // Not drawn yet → show the original emoji rather than an empty box.
  if (!shapes) return <span className={`icon-fallback ${className}`} aria-hidden>{name}</span>

  return (
    <svg className={`icon ${className}`} viewBox="0 0 24 24" aria-hidden
      fill="none" stroke="currentColor" strokeWidth="1.75"
      strokeLinecap="round" strokeLinejoin="round">
      {shapes.map((d, i) => <path key={i} d={d} />)}
    </svg>
  )
}

