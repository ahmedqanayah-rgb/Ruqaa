/*
 * Generate src/data/imageDims.js — intrinsic pixel sizes for the inline content
 * images, so `ImageBlock` can emit width/height attributes and the browser can
 * reserve the right box before the bytes arrive.
 *
 * Why a manifest and not CSS: POLISH-PLAN §1d. The book covers could take a flat
 * `aspect-ratio: 2/3` because they genuinely are all 2:3. Content images are not
 * — provincetown is 1.78, graceland 1.36 — so one ratio would distort them. The
 * only honest fix is per-image intrinsic dimensions, and those have to come from
 * the files themselves.
 *
 * Only images rendered through ImageBlock (`image` / `imggrid` blocks) are
 * included; portraits, covers and logos are already fixed-size in CSS.
 *
 * Re-run after adding or replacing a content image:
 *   node scripts/gen-image-dims.mjs
 * `node scripts/check-image-refs.mjs` reports any that are missing.
 */
import sharp from 'sharp'
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const __dirname = path.dirname(fileURLToPath(import.meta.url))
const pub = path.resolve(__dirname, '../public')
const outFile = path.resolve(__dirname, '../src/data/imageDims.js')
const { books } = await import('../src/data/books.js')

// Collect every src that reaches ImageBlock.
const srcs = new Set()
const walk = (v) => {
  if (!v || typeof v !== 'object') return
  if (Array.isArray(v)) return v.forEach(walk)
  if (v.type === 'image' && v.src) srcs.add(v.src)
  if (v.type === 'imggrid' && Array.isArray(v.images)) v.images.forEach((i) => i.src && srcs.add(i.src))
  Object.values(v).forEach(walk)
}
walk(books)

const entries = []
for (const src of [...srcs].sort()) {
  const file = path.join(pub, src.replace('./', ''))
  if (!fs.existsSync(file)) { console.warn('MISSING', src); continue }
  const { width, height } = await sharp(file).metadata()
  entries.push(`  '${src}': [${width}, ${height}],`)
}

const body = `// GENERATED by scripts/gen-image-dims.mjs — do not edit by hand.
//
// Intrinsic [width, height] for every inline content image, so ImageBlock can
// reserve its space before the image loads. Content images have genuinely
// different aspect ratios, so a single CSS aspect-ratio would distort them
// (POLISH-PLAN §1d). Re-run the script after adding or replacing one.
export const imageDims = {
${entries.join('\n')}
}
`
fs.writeFileSync(outFile, body)
console.log(`wrote ${entries.length} entries to src/data/imageDims.js`)
