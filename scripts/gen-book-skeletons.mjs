/*
 * Generate the two files through which the app knows about books it has not
 * loaded:
 *
 *   src/data/bookSkeletons.js  every book's skeleton + the club totals
 *                              (see src/data/skeleton.js for what that keeps)
 *   src/data/searchData.js     the prebuilt search index (src/data/searchBuild.js)
 *
 * Both are derived from the full books in src/data/allBooks.js, which the app
 * itself never imports — that is the point: the entry chunk carries the
 * skeletons, each book's content arrives when the book is opened, and the
 * search data arrives when the search palette is.
 *
 * RUNS BY ITSELF: package.json has it as `predev` and `prebuild`, so `npm run
 * dev` and every Vercel build regenerate them first. Committed anyway, so a
 * plain `vite` still works and a diff shows what changed.
 *
 *   node scripts/gen-book-skeletons.mjs           write both files
 *   node scripts/gen-book-skeletons.mjs --check   exit 1 if either is stale
 */
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { books } from '../src/data/allBooks.js'
import { toSkeleton, clubTotals } from '../src/data/skeleton.js'
import { buildIndex } from '../src/data/searchBuild.js'

const here = path.dirname(fileURLToPath(import.meta.url))
const out = (f) => path.resolve(here, '../src/data', f)
const check = process.argv.includes('--check')

const HEADER = (what) => `/* GENERATED by scripts/gen-book-skeletons.mjs from src/data/allBooks.js — do not
   edit by hand; edit the book and it regenerates on \`npm run dev\` / \`npm run build\`.
   ${what} */
`

const skeletons = books.map(toSkeleton)
const files = {
  'bookSkeletons.js':
    HEADER('Every book’s skeleton: what the app needs before a book is opened.') +
    `export const bookSkeletons = ${JSON.stringify(skeletons, null, 2)}\n\n` +
    `export const clubTotals = ${JSON.stringify(clubTotals(skeletons))}\n`,
  // One entry per line: diffable, and still a single literal to the bundler.
  'searchData.js':
    HEADER('The prebuilt search index, loaded when the search palette first opens.') +
    `export const searchIndex = [\n${buildIndex(books).map((e) => JSON.stringify(e)).join(',\n')}\n]\n`,
}

let stale = 0
for (const [name, text] of Object.entries(files)) {
  const file = out(name)
  const current = fs.existsSync(file) ? fs.readFileSync(file, 'utf8').replace(/\r\n/g, '\n') : null
  if (current === text) { console.log(`  up to date  ${name}`); continue }
  if (check) { console.log(`  STALE  ${name} — run: node scripts/gen-book-skeletons.mjs`); stale++; continue }
  fs.writeFileSync(file, text, 'utf8')
  console.log(`  wrote  ${name}  (${Math.round(text.length / 1024)} KB)`)
}
if (check) process.exit(stale ? 1 : 0)
